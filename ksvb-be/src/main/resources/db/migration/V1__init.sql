create table app_user (
    id            bigint generated by default as identity primary key,
    full_name     varchar(150) not null,
    email         varchar(200) not null unique,
    employee_code varchar(30),
    unit_name     varchar(150) not null,
    job_title     varchar(150),
    role          varchar(20)  not null,
    active        boolean      not null
);

create table sign_request (
    id                  bigint generated by default as identity primary key,
    version             bigint       not null,
    code                varchar(40),
    title               varchar(250) not null,
    doc_type            varchar(60)  not null,
    unit_name           varchar(150),
    description         varchar(500),
    creator_id          bigint       not null references app_user (id),
    priority            varchar(20)  not null,
    mode                varchar(10)  not null,
    status              varchar(20)  not null,
    shared              boolean      not null,
    deadline            date,
    submitted_at        timestamp,
    completed_at        timestamp,
    created_at          timestamp    not null,
    updated_at          timestamp    not null,
    message             varchar(500),
    cancellation_reason varchar(500)
);
create index ix_sign_request_status on sign_request (status);
create index ix_sign_request_creator on sign_request (creator_id);

create table participant (
    id        bigint generated by default as identity primary key,
    request_id bigint      not null references sign_request (id) on delete cascade,
    user_id   bigint       not null references app_user (id),
    order_no  integer      not null,
    status    varchar(20)  not null,
    signed_at timestamp,
    note      varchar(500)
);
create index ix_participant_request on participant (request_id);
create index ix_participant_user_status on participant (user_id, status);

create table sign_request_watcher (
    request_id bigint not null references sign_request (id) on delete cascade,
    user_id    bigint not null references app_user (id),
    primary key (request_id, user_id)
);

create table attachment (
    id            bigint generated by default as identity primary key,
    request_id    bigint       not null references sign_request (id) on delete cascade,
    original_name varchar(255) not null,
    stored_name   varchar(100) not null,
    size_bytes    bigint       not null,
    signable      boolean      not null,
    uploaded_at   timestamp    not null
);
create index ix_attachment_request on attachment (request_id);

create table sign_template (
    id         bigint generated by default as identity primary key,
    name       varchar(150) not null,
    mode       varchar(10)  not null,
    used_count integer      not null,
    owner_id   bigint       not null references app_user (id)
);

create table sign_template_signer (
    template_id  bigint  not null references sign_template (id) on delete cascade,
    signer_order integer not null,
    user_id      bigint  not null,
    primary key (template_id, signer_order)
);

create table doc_counter (
    counter_key varchar(60) primary key,
    last_value  integer not null
);

create table audit_log (
    id       bigint generated by default as identity primary key,
    occurred_at timestamp  not null,
    actor_id bigint,
    action   varchar(60)  not null,
    target   varchar(120),
    detail   varchar(500)
);
create index ix_audit_log_at on audit_log (occurred_at);
